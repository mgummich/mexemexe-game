let current: Locale = 'pt';

export function setLocale(l: Locale): void {
  current = l;
}

export function getLocale(): Locale {
  return current;
}

/** Every key defined for one locale — test-only (key-parity checks); `t()` never needs this. */
export function localeKeys(l: Locale): string[] {
  return Object.keys(dict[l]);
}

export function t(key: string, params?: Record<string, string | number>): string {
  let s = dict[current][key] ?? dict.pt[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}
